import { writeFile } from 'node:fs/promises';
import { URL } from 'node:url';
import { log } from 'node:console';

// Charlie distribution and visibility from KHR_materials_sheen. Uniform midpoint
// quadrature over cos(theta) and azimuth integrates BRDF * NdotL over the hemisphere.
const size = 32;
const elevations = 128;
const azimuths = 256;
const values = [];
function logLambda(x, alpha) {
  const t = (1 - alpha) ** 2;
  const a = 21.5473 + (25.3245 - 21.5473) * t;
  const b = 3.82987 + (3.32435 - 3.82987) * t;
  const c = 0.19823 + (0.16801 - 0.19823) * t;
  const d = -1.9776 + (-1.27393 + 1.9776) * t;
  const e = -4.32054 + (-4.85967 + 4.32054) * t;
  return a / (1 + b * x ** c) + d * x + e;
}
function lambda(x, alpha) {
  return Math.exp(
    x < 0.5
      ? logLambda(x, alpha)
      : 2 * logLambda(0.5, alpha) - logLambda(1 - x, alpha),
  );
}
for (let y = 0; y < size; y++) {
  const alpha = ((y + 0.5) / size) ** 2;
  const inverse = 1 / alpha;
  for (let x = 0; x < size; x++) {
    const nv = (x + 0.5) / size;
    const sv = Math.sqrt(1 - nv * nv);
    const lv = lambda(nv, alpha);
    let energy = 0;
    for (let elevation = 0; elevation < elevations; elevation++) {
      const nl = (elevation + 0.5) / elevations;
      const sl = Math.sqrt(1 - nl * nl);
      const visibility = 1 / ((1 + lv + lambda(nl, alpha)) * 4 * nv);
      for (let azimuth = 0; azimuth < azimuths; azimuth++) {
        const vl =
          sv * sl * Math.cos(((azimuth + 0.5) * 2 * Math.PI) / azimuths) +
          nv * nl;
        const nh2 = (nv + nl) ** 2 / (2 + 2 * vl);
        const distribution =
          ((2 + inverse) * Math.max(0, 1 - nh2) ** (inverse * 0.5)) /
          (2 * Math.PI);
        energy += distribution * visibility;
      }
    }
    values.push(
      Math.fround(
        Math.min(1, (energy * 2 * Math.PI) / (elevations * azimuths)),
      ),
    );
  }
}
await writeFile(
  new URL('../src/data/sheen.ts', import.meta.url),
  '// Generated by scripts/generate-sheen-lut.mjs; do not edit the samples.\n' +
    '// Rows: perceptual roughness; columns: NdotV. Midpoint grid, Charlie visibility.\n' +
    `export const SHEEN_LUT_SIZE = ${size};\nexport const sheenDirectionalAlbedo = new Float32Array([\n` +
    values.map((value) => `  ${value.toPrecision(9)},`).join('\n') +
    '\n]);\n',
);
log(
  `Generated ${size}x${size} Charlie directional-albedo samples (${elevations}x${azimuths} quadrature).`,
);
