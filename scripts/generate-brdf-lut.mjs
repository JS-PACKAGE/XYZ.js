import { writeFile } from 'node:fs/promises';
import { URL } from 'node:url';
import { log } from 'node:console';

// NDF importance sampling integrates Schlick A/B with height-correlated Smith GGX.
// Two packed channels fit the guaranteed 16 KiB uniform-block limit, without a sampler.
const width = 64;
const height = 32;
const samples = 65536;
const cosine = new Float64Array(samples);
const sequence = new Float64Array(samples);
for (let i = 0; i < samples; i++) {
  const phi = ((i + 0.5) * 2 * Math.PI) / samples;
  cosine[i] = Math.cos(phi);
  let bits = i,
    inverse = 0,
    place = 0.5;
  while (bits) {
    inverse += (bits & 1) * place;
    bits >>>= 1;
    place *= 0.5;
  }
  sequence[i] = inverse;
}
const values = [];
for (let y = 0; y < height; y++) {
  const roughness = y / (height - 1),
    alpha2 = roughness ** 4;
  const halfCosine = new Float64Array(samples),
    halfSine = new Float64Array(samples);
  for (let i = 0; i < samples; i++) {
    const u = sequence[i];
    halfCosine[i] = Math.sqrt((1 - u) / (1 + (alpha2 - 1) * u));
    halfSine[i] = Math.sqrt(Math.max(0, 1 - halfCosine[i] ** 2));
  }
  for (let x = 0; x < width; x++) {
    const nv = Math.max(0.0001, x / (width - 1)),
      sv = Math.sqrt(1 - nv * nv);
    const rootV = Math.sqrt(alpha2 + (1 - alpha2) * nv * nv);
    let a = 0,
      b = 0;
    for (let i = 0; i < samples; i++) {
      const nh = halfCosine[i],
        vh = sv * halfSine[i] * cosine[i] + nv * nh;
      const nl = 2 * vh * nh - nv;
      if (vh <= 0 || nl <= 0) continue;
      const rootL = Math.sqrt(alpha2 + (1 - alpha2) * nl * nl);
      const visibility = (2 * nl * vh) / (nh * (nl * rootV + nv * rootL));
      const fresnel = (1 - Math.min(1, vh)) ** 5;
      a += (1 - fresnel) * visibility;
      b += fresnel * visibility;
    }
    values.push(Math.fround(a / samples), Math.fround(b / samples));
  }
}
await writeFile(
  new URL('../src/data/brdf.ts', import.meta.url),
  '// Generated by scripts/generate-brdf-lut.mjs; do not edit the samples.\n' +
    '// Endpoint grid: rows perceptual roughness, columns NdotV (zero regularized to 1e-4).\n' +
    `export const BRDF_LUT_WIDTH = ${width};\nexport const BRDF_LUT_HEIGHT = ${height};\n` +
    'export const ggxDirectionalAlbedo = new Float32Array([\n' +
    values.map((value) => `  ${value.toPrecision(9)},`).join('\n') +
    '\n]);\n',
);
log(
  `Generated ${width}x${height} GGX A/B samples (${samples} deterministic samples each, ${values.length * 4} uniform bytes).`,
);
